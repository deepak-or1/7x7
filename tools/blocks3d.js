#!/usr/bin/env node
// Makes js/map3d/blocks.js: the outline of every place's block on the 3D map, worked out ahead of time (about a second of work
// that the page would otherwise do before its first 3D frame). Run it by hand after data/geo.js or the outline recipe in
// js/map3d/land.js changes:
//
//   node tools/blocks3d.js
//
// It runs the page's own code (js/geom.js, js/map3d/land.js) on the page's own data, so the result is what the page would make
// itself; the file carries a signature of the boundaries it was made from, and the page makes its own outlines when that does
// not match. No packages.
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const win = {}; const ctx = vm.createContext({ window: win, console, performance, Math, Float32Array, Uint8Array, Map, Set });
for (const f of ['data/geo.js', 'data/info.js', 'js/geom.js', 'js/map3d/land.js']) vm.runInContext(fs.readFileSync(path.join(root, f), 'utf8'), ctx, { filename: f });
const land = win.M3D.land, t0 = Date.now(), packed = land.pack(land.outlines());
let rings = 0, pts = 0; packed.blocks.forEach(pieces => pieces.forEach(rs => rs.forEach(r => { rings++; pts += r.length / 2; })));
const out = '// Generated by tools/blocks3d.js (do not edit by hand): the outline of every place\'s block on the 3D map, from data/geo.js by the\n'
  + '// recipe in js/map3d/land.js. Per place: its pieces; per piece: the outer ring, then its holes; per ring: x, y of the first point,\n'
  + '// then steps, in hundredths of a map unit. sig: the boundaries this was made from (land.js makes its own outlines when it differs).\n'
  + 'window.M3D_BLOCKS = ' + JSON.stringify(packed) + ';\n';
fs.mkdirSync(path.join(root, 'js/map3d'), { recursive: true });
fs.writeFileSync(path.join(root, 'js/map3d/blocks.js'), out);
console.log(`js/map3d/blocks.js: ${packed.blocks.length} places, ${rings} rings, ${pts} points, ${(out.length / 1024).toFixed(0)} KB, signature ${packed.sig}, ${Date.now() - t0} ms`);
